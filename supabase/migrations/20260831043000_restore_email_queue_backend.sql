CREATE OR REPLACE FUNCTION private.prune_email_operational_data()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
  deleted_logs bigint;
  deleted_claims bigint;
BEGIN
  DELETE FROM public.email_send_log
  WHERE created_at < now() - interval '90 days';
  GET DIAGNOSTICS deleted_logs = ROW_COUNT;

  DELETE FROM public.email_enqueue_claims
  WHERE created_at < now() - interval '365 days';
  GET DIAGNOSTICS deleted_claims = ROW_COUNT;

  RETURN jsonb_build_object(
    'deleted_logs', deleted_logs,
    'deleted_claims', deleted_claims
  );
END
$function$;

CREATE OR REPLACE FUNCTION private.install_email_queue_schedules()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, cron, net, vault
AS $function$
DECLARE
  worker_job_id bigint;
  retention_job_id bigint;
  has_project_url boolean;
  has_service_key boolean;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM vault.decrypted_secrets
    WHERE name = 'habtastic_project_url'
      AND nullif(decrypted_secret, '') IS NOT NULL
  ) INTO has_project_url;

  SELECT EXISTS (
    SELECT 1 FROM vault.decrypted_secrets
    WHERE name = 'habtastic_email_worker_service_role'
      AND nullif(decrypted_secret, '') IS NOT NULL
  ) INTO has_service_key;

  IF NOT has_project_url OR NOT has_service_key THEN
    RAISE EXCEPTION
      'Provision Vault secrets habtastic_project_url and habtastic_email_worker_service_role before scheduling';
  END IF;

  PERFORM cron.unschedule(jobid)
  FROM cron.job
  WHERE jobname IN (
    'habtastic-process-email-queue',
    'habtastic-prune-email-operational-data'
  );

  SELECT cron.schedule(
    'habtastic-process-email-queue',
    '* * * * *',
    $cron$
      SELECT net.http_post(
        url := (
          SELECT decrypted_secret
          FROM vault.decrypted_secrets
          WHERE name = 'habtastic_project_url'
        ) || '/functions/v1/process-email-queue',
        headers := jsonb_build_object(
          'Content-Type', 'application/json',
          'Authorization', 'Bearer ' || (
            SELECT decrypted_secret
            FROM vault.decrypted_secrets
            WHERE name = 'habtastic_email_worker_service_role'
          )
        ),
        body := '{}'::jsonb
      );
    $cron$
  ) INTO worker_job_id;

  SELECT cron.schedule(
    'habtastic-prune-email-operational-data',
    '17 3 * * *',
    $cron$
      SELECT private.prune_email_operational_data();
    $cron$
  ) INTO retention_job_id;

  RETURN jsonb_build_object(
    'worker_job_id', worker_job_id,
    'retention_job_id', retention_job_id
  );
END
$function$;

REVOKE ALL ON FUNCTION private.prune_email_operational_data() FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION private.install_email_queue_schedules() FROM PUBLIC, anon, authenticated, service_role;

COMMENT ON FUNCTION private.install_email_queue_schedules() IS
  'Manually installs the email worker and retention schedules after Vault secrets are provisioned. The cron command references Vault by name and never stores decrypted values in cron.job.';
