CREATE OR REPLACE FUNCTION public.move_to_dlq(
  source_queue text,
  dlq_name text,
  message_id bigint,
  payload jsonb
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pgmq
AS $function$
DECLARE
  deleted boolean;
BEGIN
  IF NOT (
    (source_queue = 'auth_emails' AND dlq_name = 'auth_emails_dlq')
    OR
    (source_queue = 'transactional_emails' AND dlq_name = 'transactional_emails_dlq')
  ) THEN
    RAISE EXCEPTION 'Unsupported email DLQ mapping' USING ERRCODE = '22023';
  END IF;
  IF payload IS NULL OR jsonb_typeof(payload) <> 'object' THEN
    RAISE EXCEPTION 'DLQ payload must be a JSON object' USING ERRCODE = '22023';
  END IF;

  -- Both operations share the caller's transaction. If the DLQ send fails,
  -- the source deletion is rolled back and the message remains recoverable.
  SELECT pgmq.delete(move_to_dlq.source_queue, move_to_dlq.message_id)
  INTO deleted;
  IF NOT coalesce(deleted, false) THEN
    RETURN false;
  END IF;

  PERFORM pgmq.send(move_to_dlq.dlq_name, move_to_dlq.payload);
  RETURN true;
END
$function$;

