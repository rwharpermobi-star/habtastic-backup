-- Restore the durable email backend that was lost during the July 2026
-- database rebuild. This migration deliberately does not create a cron job:
-- the worker schedule is installed only after the required Vault secrets have
-- been provisioned and `private.install_email_queue_schedules()` is called.

CREATE EXTENSION IF NOT EXISTS pgmq;
CREATE EXTENSION IF NOT EXISTS pg_cron;
CREATE EXTENSION IF NOT EXISTS pg_net;

CREATE TABLE IF NOT EXISTS public.email_send_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  message_id text,
  template_name text NOT NULL CHECK (char_length(template_name) BETWEEN 1 AND 120),
  recipient_email text NOT NULL CHECK (char_length(recipient_email) BETWEEN 3 AND 320),
  status text NOT NULL CHECK (
    status IN (
      'pending',
      'sent',
      'failed',
      'rate_limited',
      'dlq',
      'suppressed',
      'bounced',
      'complained'
    )
  ),
  error_message text,
  metadata jsonb,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS email_send_log_message_status_idx
  ON public.email_send_log (message_id, status)
  WHERE message_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS email_send_log_one_sent_per_message_idx
  ON public.email_send_log (message_id)
  WHERE message_id IS NOT NULL AND status = 'sent';

CREATE INDEX IF NOT EXISTS email_send_log_created_at_idx
  ON public.email_send_log (created_at);

CREATE TABLE IF NOT EXISTS public.email_send_state (
  id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  retry_after_until timestamptz,
  batch_size integer NOT NULL DEFAULT 10 CHECK (batch_size BETWEEN 1 AND 50),
  send_delay_ms integer NOT NULL DEFAULT 200 CHECK (send_delay_ms BETWEEN 0 AND 5000),
  visibility_timeout_seconds integer NOT NULL DEFAULT 180
    CHECK (visibility_timeout_seconds BETWEEN 30 AND 900),
  auth_email_ttl_minutes integer NOT NULL DEFAULT 15
    CHECK (auth_email_ttl_minutes BETWEEN 1 AND 1440),
  transactional_email_ttl_minutes integer NOT NULL DEFAULT 60
    CHECK (transactional_email_ttl_minutes BETWEEN 1 AND 10080),
  updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO public.email_send_state (id)
VALUES (1)
ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.suppressed_emails (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE CHECK (
    email = lower(email)
    AND char_length(email) BETWEEN 3 AND 320
  ),
  reason text NOT NULL CHECK (reason IN ('bounce', 'complaint', 'unsubscribe', 'manual')),
  metadata jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.email_unsubscribe_tokens (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  email text NOT NULL UNIQUE CHECK (
    email = lower(email)
    AND char_length(email) BETWEEN 3 AND 320
  ),
  token text NOT NULL UNIQUE CHECK (token ~ '^[0-9a-f]{64}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  used_at timestamptz
);

-- An enqueue claim makes retries idempotent before they reach the provider.
-- The queue name is part of the key so auth and transactional identifiers do
-- not collide. This table never stores message bodies or email addresses.
CREATE TABLE IF NOT EXISTS public.email_enqueue_claims (
  queue_name text NOT NULL CHECK (queue_name IN ('auth_emails', 'transactional_emails')),
  idempotency_key text NOT NULL CHECK (char_length(idempotency_key) BETWEEN 1 AND 500),
  message_id text NOT NULL,
  queue_message_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (queue_name, idempotency_key)
);

DO $queue_setup$
BEGIN
  IF to_regclass('pgmq.q_auth_emails') IS NULL THEN
    PERFORM pgmq.create('auth_emails');
  END IF;
  IF to_regclass('pgmq.q_transactional_emails') IS NULL THEN
    PERFORM pgmq.create('transactional_emails');
  END IF;
  IF to_regclass('pgmq.q_auth_emails_dlq') IS NULL THEN
    PERFORM pgmq.create('auth_emails_dlq');
  END IF;
  IF to_regclass('pgmq.q_transactional_emails_dlq') IS NULL THEN
    PERFORM pgmq.create('transactional_emails_dlq');
  END IF;
END
$queue_setup$;

CREATE OR REPLACE FUNCTION public.enqueue_email(
  queue_name text,
  payload jsonb
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, pgmq
AS $function$
DECLARE
  dedupe_key text;
  owns_claim boolean := false;
  queued_message_id bigint;
BEGIN
  IF queue_name NOT IN ('auth_emails', 'transactional_emails') THEN
    RAISE EXCEPTION 'Unsupported email queue' USING ERRCODE = '22023';
  END IF;
  IF payload IS NULL OR jsonb_typeof(payload) <> 'object' THEN
    RAISE EXCEPTION 'Email payload must be a JSON object' USING ERRCODE = '22023';
  END IF;
  IF coalesce(payload->>'message_id', '') = ''
     OR coalesce(payload->>'to', '') = ''
     OR coalesce(payload->>'subject', '') = '' THEN
    RAISE EXCEPTION 'Email payload is missing required fields' USING ERRCODE = '22023';
  END IF;

  dedupe_key := coalesce(
    nullif(btrim(payload->>'idempotency_key'), ''),
    nullif(btrim(payload->>'run_id'), '')
  );

  IF dedupe_key IS NOT NULL THEN
    IF char_length(dedupe_key) > 500 THEN
      RAISE EXCEPTION 'Email idempotency key is too long' USING ERRCODE = '22023';
    END IF;

    INSERT INTO public.email_enqueue_claims (
      queue_name,
      idempotency_key,
      message_id
    )
    VALUES (
      enqueue_email.queue_name,
      dedupe_key,
      payload->>'message_id'
    )
    ON CONFLICT (queue_name, idempotency_key) DO NOTHING
    RETURNING true INTO owns_claim;

    IF NOT coalesce(owns_claim, false) THEN
      SELECT claim.queue_message_id
      INTO queued_message_id
      FROM public.email_enqueue_claims AS claim
      WHERE claim.queue_name = enqueue_email.queue_name
        AND claim.idempotency_key = dedupe_key;

      IF queued_message_id IS NULL THEN
        RAISE EXCEPTION 'Existing email enqueue claim is incomplete';
      END IF;
      RETURN queued_message_id;
    END IF;
  END IF;

  SELECT pgmq.send(enqueue_email.queue_name, payload)
  INTO queued_message_id;

  IF dedupe_key IS NOT NULL THEN
    UPDATE public.email_enqueue_claims AS claim
    SET queue_message_id = queued_message_id
    WHERE claim.queue_name = enqueue_email.queue_name
      AND claim.idempotency_key = dedupe_key;
  END IF;

  RETURN queued_message_id;
END
$function$;

CREATE OR REPLACE FUNCTION public.read_email_batch(
  queue_name text,
  batch_size integer,
  p_visibility_timeout integer
)
RETURNS TABLE (
  msg_id bigint,
  read_ct integer,
  enqueued_at timestamptz,
  vt timestamptz,
  message jsonb
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pgmq
AS $function$
BEGIN
  IF queue_name NOT IN ('auth_emails', 'transactional_emails') THEN
    RAISE EXCEPTION 'Unsupported email queue' USING ERRCODE = '22023';
  END IF;
  IF batch_size NOT BETWEEN 1 AND 50 THEN
    RAISE EXCEPTION 'Invalid email batch size' USING ERRCODE = '22023';
  END IF;
  IF p_visibility_timeout NOT BETWEEN 30 AND 900 THEN
    RAISE EXCEPTION 'Invalid email visibility timeout' USING ERRCODE = '22023';
  END IF;

  RETURN QUERY
  SELECT item.msg_id, item.read_ct, item.enqueued_at, item.vt, item.message
  FROM pgmq.read(read_email_batch.queue_name, read_email_batch.p_visibility_timeout, read_email_batch.batch_size) AS item;
END
$function$;

